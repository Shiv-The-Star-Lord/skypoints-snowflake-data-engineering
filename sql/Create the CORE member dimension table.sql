
USE DATABASE SKYPOINTS_DE;
USE SCHEMA CORE;

CREATE TABLE IF NOT EXISTS SKYPOINTS_DE.CORE.MEMBER_PROFILE
(
    MEMBER_SK_KEY       NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    MEMBER_NAME         VARCHAR(255),
    MEMBER_ID           VARCHAR(100),
    DATE_OF_BIRTH       DATE,
    AGE                 NUMBER(3,0),
    TIER_CODE           VARCHAR(50),
    ENROLLMENT_DATE     DATE,
    LAST_FLIGHT_DATE    DATE,
    STALE_MEMBER        BOOLEAN,
    AGENT_NAME          VARCHAR(255),
    STATE_CODE          VARCHAR(100),
    POSTAL_CODE         VARCHAR(50),
    IS_ACTIVE           VARCHAR(10),
    MEMBER_TYPE         VARCHAR(100),
    COUNTRY_CODE        VARCHAR(10),

    RECORD_HASH         VARCHAR(64),

    EFFECTIVE_FROM      TIMESTAMP_NTZ,
    EFFECTIVE_TO        TIMESTAMP_NTZ,
    IS_CURRENT          BOOLEAN,

    CREATED_TIMESTAMP   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

DESC TABLE SKYPOINTS_DE.CORE.MEMBER_PROFILE;
