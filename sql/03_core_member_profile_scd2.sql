INSERT INTO SKYPOINTS_DE.CORE.MEMBER_PROFILE
(
    MEMBER_NAME,
    MEMBER_ID,
    DATE_OF_BIRTH,
    AGE,
    TIER_CODE,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    STALE_MEMBER,
    AGENT_NAME,
    STATE_CODE,
    POSTAL_CODE,
    IS_ACTIVE,
    MEMBER_TYPE,
    COUNTRY_CODE,
    RECORD_HASH,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT
)
WITH VERSIONED_DATA AS
(
    SELECT
        MEMBER_NAME,
        MEMBER_ID,
        DATE_OF_BIRTH,
        AGE,
        TIER_CODE,
        ENROLLMENT_DATE,
        LAST_FLIGHT_DATE,
        STALE_MEMBER,
        AGENT_NAME,
        STATE_CODE,
        POSTAL_CODE,
        IS_ACTIVE,
        MEMBER_TYPE,
        COUNTRY_CODE,
        RECORD_HASH,
        INGESTION_TIMESTAMP AS EFFECTIVE_FROM,

        LEAD(INGESTION_TIMESTAMP) OVER
        (
            PARTITION BY MEMBER_NAME
            ORDER BY INGESTION_TIMESTAMP, BATCH_ID, SOURCE_ROW_NUMBER
        ) AS EFFECTIVE_TO

    FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES
)
SELECT
    MEMBER_NAME,
    MEMBER_ID,
    DATE_OF_BIRTH,
    AGE,
    TIER_CODE,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    STALE_MEMBER,
    AGENT_NAME,
    STATE_CODE,
    POSTAL_CODE,
    IS_ACTIVE,
    MEMBER_TYPE,
    COUNTRY_CODE,
    RECORD_HASH,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    CASE
        WHEN EFFECTIVE_TO IS NULL THEN TRUE
        ELSE FALSE
    END AS IS_CURRENT
FROM VERSIONED_DATA;
