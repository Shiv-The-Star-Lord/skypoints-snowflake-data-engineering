USE DATABASE SKYPOINTS_DE;


CREATE OR REPLACE TEMPORARY TABLE PENDING_MEMBER_VERSIONS AS
SELECT
    S.*,
    LEAD(S.INGESTION_TIMESTAMP) OVER
    (
        PARTITION BY S.MEMBER_NAME
        ORDER BY
            S.INGESTION_TIMESTAMP,
            S.BATCH_ID,
            S.SOURCE_ROW_NUMBER
    ) AS NEXT_EFFECTIVE_FROM
FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES S
WHERE NOT EXISTS
(
    SELECT 1
    FROM SKYPOINTS_DE.CORE.MEMBER_PROFILE C
    WHERE C.SOURCE_BATCH_ID = S.BATCH_ID
      AND C.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER
);



SELECT
    MEMBER_NAME,
    MEMBER_ID,
    BATCH_ID,
    SOURCE_ROW_NUMBER,
    INGESTION_TIMESTAMP,
    NEXT_EFFECTIVE_FROM
FROM PENDING_MEMBER_VERSIONS;



UPDATE SKYPOINTS_DE.CORE.MEMBER_PROFILE C
SET
    EFFECTIVE_TO = P.FIRST_NEW_EFFECTIVE_FROM,
    IS_CURRENT = FALSE
FROM
(
    SELECT
        MEMBER_NAME,
        MIN(INGESTION_TIMESTAMP) AS FIRST_NEW_EFFECTIVE_FROM
    FROM PENDING_MEMBER_VERSIONS
    GROUP BY MEMBER_NAME
) P
WHERE C.MEMBER_NAME = P.MEMBER_NAME
  AND C.IS_CURRENT = TRUE;




