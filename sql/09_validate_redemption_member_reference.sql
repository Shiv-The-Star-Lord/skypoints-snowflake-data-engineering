USE DATABASE SKYPOINTS_DE;

SELECT
    r.MEMBER_ID,
    COUNT(*) AS UNMATCHED_TRANSACTIONS,
    SUM(r.MILES_REDEEMED) AS UNMATCHED_MILES
FROM CORE.REDEMPTION_TRANSACTIONS r
LEFT JOIN CORE.MEMBER_PROFILE m
    ON r.MEMBER_ID = m.MEMBER_ID
   AND m.IS_CURRENT = TRUE
WHERE m.MEMBER_ID IS NULL
GROUP BY r.MEMBER_ID;