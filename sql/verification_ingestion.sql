SELECT
    C.MEMBER_NAME,
    C.AGENT_NAME AS EXISTING_AGENT,
    C.IS_CURRENT,
    P.FIRST_NEW_EFFECTIVE_FROM
FROM SKYPOINTS_DE.CORE.MEMBER_PROFILE C
JOIN
(
    SELECT
        MEMBER_NAME,
        MIN(INGESTION_TIMESTAMP) AS FIRST_NEW_EFFECTIVE_FROM
    FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES S
    WHERE NOT EXISTS
    (
        SELECT 1
        FROM SKYPOINTS_DE.CORE.MEMBER_PROFILE X
        WHERE X.SOURCE_BATCH_ID = S.BATCH_ID
          AND X.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER
    )
    GROUP BY MEMBER_NAME
) P
    ON C.MEMBER_NAME = P.MEMBER_NAME
WHERE C.IS_CURRENT = TRUE;




