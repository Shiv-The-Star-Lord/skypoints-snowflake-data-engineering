USE DATABASE SKYPOINTS_DE;
USE SCHEMA RAW;




SELECT
    'RAW_MEMBER_PROFILES' AS TABLE_NAME,
    COUNT(*) AS RECORD_COUNT
FROM SKYPOINTS_DE.RAW.RAW_MEMBER_PROFILES

UNION ALL

SELECT
    'INGESTION_AUDIT' AS TABLE_NAME,
    COUNT(*) AS RECORD_COUNT
FROM SKYPOINTS_DE.OPS.INGESTION_AUDIT;


SELECT
    MEMBER_NAME,
    MEMBER_ID,
    COUNTRY_CODE,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    BATCH_ID
FROM SKYPOINTS_DE.RAW.RAW_MEMBER_PROFILES
WHERE BATCH_ID = 'dd1f3b54-5d2b-452c-b974-57a50414d9b0'
ORDER BY SOURCE_ROW_NUMBER;



SELECT
    BATCH_ID,
    SOURCE_ID,
    SOURCE_FILE,
    FILE_CHECKSUM,
    RECORD_COUNT,
    STATUS,
    STARTED_AT,
    COMPLETED_AT,
    ERROR_MESSAGE
FROM SKYPOINTS_DE.OPS.INGESTION_AUDIT
WHERE BATCH_ID = 'dd1f3b54-5d2b-452c-b974-57a50414d9b0';



SELECT
    STATUS,
    COUNT(*) AS ATTEMPT_COUNT
FROM SKYPOINTS_DE.OPS.INGESTION_AUDIT
GROUP BY STATUS
ORDER BY STATUS;




SELECT COUNT(*) AS RAW_RECORD_COUNT
FROM SKYPOINTS_DE.RAW.RAW_MEMBER_PROFILES;



SELECT
    COUNT(*) AS TOTAL_RAW_RECORDS,
    COUNT(DISTINCT MEMBER_ID) AS DISTINCT_MEMBERS
FROM SKYPOINTS_DE.RAW.RAW_MEMBER_PROFILES;



SELECT
    STATUS,
    COUNT(*) AS ATTEMPT_COUNT
FROM SKYPOINTS_DE.OPS.INGESTION_AUDIT
GROUP BY STATUS
ORDER BY STATUS;



SELECT
    MEMBER_NAME,
    MEMBER_ID,
    COUNTRY_CODE,
    INGESTION_TIMESTAMP,
    SOURCE_FILE,
    BATCH_ID
FROM SKYPOINTS_DE.RAW.RAW_MEMBER_PROFILES
ORDER BY INGESTION_TIMESTAMP, SOURCE_ROW_NUMBER;


SHOW TABLES IN SCHEMA SKYPOINTS_DE.STG;