
USE DATABASE SKYPOINTS_DE;
USE SCHEMA CORE;

BEGIN TRANSACTION;

-- 1. India
MERGE INTO MEMBER_PROFILE_IND T
USING (
    SELECT *
    FROM MEMBER_PROFILE
    WHERE IS_CURRENT = TRUE
      AND COUNTRY_CODE = 'IND'
) S
ON T.MEMBER_NAME = S.MEMBER_NAME

WHEN MATCHED AND (
       T.RECORD_HASH IS DISTINCT FROM S.RECORD_HASH
    OR T.AGE IS DISTINCT FROM S.AGE
    OR T.STALE_MEMBER IS DISTINCT FROM S.STALE_MEMBER
)
THEN UPDATE SET
    T.MEMBER_SK_KEY = S.MEMBER_SK_KEY,
    T.MEMBER_ID = S.MEMBER_ID,
    T.DATE_OF_BIRTH = S.DATE_OF_BIRTH,
    T.TIER_CODE = S.TIER_CODE,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.LAST_FLIGHT_DATE = S.LAST_FLIGHT_DATE,
    T.AGENT_NAME = S.AGENT_NAME,
    T.STATE_CODE = S.STATE_CODE,
    T.POSTAL_CODE = S.POSTAL_CODE,
    T.IS_ACTIVE = S.IS_ACTIVE,
    T.MEMBER_TYPE = S.MEMBER_TYPE,
    T.COUNTRY_CODE = S.COUNTRY_CODE,
    T.RECORD_HASH = S.RECORD_HASH,
    T.EFFECTIVE_FROM = S.EFFECTIVE_FROM,
    T.EFFECTIVE_TO = S.EFFECTIVE_TO,
    T.IS_CURRENT = S.IS_CURRENT,
    T.CREATED_TIMESTAMP = S.CREATED_TIMESTAMP,
    T.SOURCE_BATCH_ID = S.SOURCE_BATCH_ID,
    T.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER

WHEN NOT MATCHED THEN INSERT (
    MEMBER_SK_KEY, MEMBER_NAME, MEMBER_ID, DATE_OF_BIRTH,
    TIER_CODE, ENROLLMENT_DATE, LAST_FLIGHT_DATE, AGENT_NAME,
    STATE_CODE, POSTAL_CODE, IS_ACTIVE, MEMBER_TYPE,
    COUNTRY_CODE, RECORD_HASH, EFFECTIVE_FROM, EFFECTIVE_TO,
    IS_CURRENT, CREATED_TIMESTAMP, SOURCE_BATCH_ID,
    SOURCE_ROW_NUMBER, AGE, STALE_MEMBER
)
VALUES (
    S.MEMBER_SK_KEY, S.MEMBER_NAME, S.MEMBER_ID, S.DATE_OF_BIRTH,
    S.TIER_CODE, S.ENROLLMENT_DATE, S.LAST_FLIGHT_DATE, S.AGENT_NAME,
    S.STATE_CODE, S.POSTAL_CODE, S.IS_ACTIVE, S.MEMBER_TYPE,
    S.COUNTRY_CODE, S.RECORD_HASH, S.EFFECTIVE_FROM, S.EFFECTIVE_TO,
    S.IS_CURRENT, S.CREATED_TIMESTAMP, S.SOURCE_BATCH_ID,
    S.SOURCE_ROW_NUMBER, S.AGE, S.STALE_MEMBER
);

DELETE FROM MEMBER_PROFILE_IND T
WHERE NOT EXISTS (
    SELECT 1
    FROM MEMBER_PROFILE S
    WHERE S.MEMBER_NAME = T.MEMBER_NAME
      AND S.IS_CURRENT = TRUE
      AND S.COUNTRY_CODE = 'IND'
);


