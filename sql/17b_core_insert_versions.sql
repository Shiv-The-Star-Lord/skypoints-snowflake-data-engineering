INSERT INTO __MEMBER_CORE_TABLE__
(
    MEMBER_NAME,
    MEMBER_ID,
    DATE_OF_BIRTH,
    AGE,
    TIER_CODE,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    STALE_MEMBER,
    AGENT_NAME,
    STATE_CODE,
    POSTAL_CODE,
    IS_ACTIVE,
    MEMBER_TYPE,
    COUNTRY_CODE,
    RECORD_HASH,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    SOURCE_BATCH_ID,
    SOURCE_ROW_NUMBER
)

SELECT
    P.MEMBER_NAME,
    P.MEMBER_ID,
    P.DATE_OF_BIRTH,
    P.AGE,
    P.TIER_CODE,
    P.ENROLLMENT_DATE,
    P.LAST_FLIGHT_DATE,
    P.STALE_MEMBER,
    P.AGENT_NAME,
    P.STATE_CODE,
    P.POSTAL_CODE,
    P.IS_ACTIVE,
    P.MEMBER_TYPE,
    P.COUNTRY_CODE,
    P.RECORD_HASH,
    P.INGESTION_TIMESTAMP,
    P.NEXT_EFFECTIVE_FROM,

    CASE
        WHEN P.NEXT_EFFECTIVE_FROM IS NULL THEN TRUE
        ELSE FALSE
    END,

    P.BATCH_ID,
    P.SOURCE_ROW_NUMBER

FROM
(
    SELECT
        S.*,

        LEAD(S.INGESTION_TIMESTAMP) OVER
        (
            PARTITION BY S.COUNTRY_CODE, S.MEMBER_ID
            ORDER BY
                S.INGESTION_TIMESTAMP,
                S.BATCH_ID,
                S.SOURCE_ROW_NUMBER
        ) AS NEXT_EFFECTIVE_FROM

    FROM __MEMBER_STAGING_TABLE__ S

    INNER JOIN __MEMBER_BATCH_CONTROL_TABLE__ B
        ON S.BATCH_ID = B.BATCH_ID

    WHERE B.STG_STATUS = 'SUCCESS'
      AND B.CORE_STATUS IN ('PENDING', 'FAILED')

      AND NOT EXISTS
      (
          SELECT 1
          FROM __MEMBER_CORE_TABLE__ C
          WHERE C.SOURCE_BATCH_ID = S.BATCH_ID
            AND C.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER
      )

) P;
