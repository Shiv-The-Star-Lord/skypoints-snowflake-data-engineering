USE DATABASE SKYPOINTS_DE;
USE SCHEMA OPS;

INSERT INTO MEMBER_BATCH_CONTROL
(
    BATCH_ID,
    SOURCE_ID,
    SOURCE_FILE,
    STG_STATUS,
    STG_STARTED_AT,
    STG_COMPLETED_AT,
    CORE_STATUS,
    CORE_STARTED_AT,
    CORE_COMPLETED_AT
)
SELECT
    A.BATCH_ID,
    A.SOURCE_ID,
    A.SOURCE_FILE,
    'SUCCESS',
    A.STARTED_AT,
    A.COMPLETED_AT,
    'SUCCESS',
    A.STARTED_AT,
    A.COMPLETED_AT
FROM OPS.INGESTION_AUDIT A
WHERE A.ENTITY_TYPE = 'MEMBER_PROFILE'
  AND A.STATUS = 'SUCCESS'
  AND EXISTS
  (
      SELECT 1
      FROM STG.STG_MEMBER_PROFILES S
      WHERE S.BATCH_ID = A.BATCH_ID
  )
  AND NOT EXISTS
  (
      SELECT 1
      FROM OPS.MEMBER_BATCH_CONTROL C
      WHERE C.BATCH_ID = A.BATCH_ID
  );