
-- ============================================================
-- PROJECT: SKYPOINTS
-- LAYER: CORE
-- PURPOSE: Expire current records for pending CORE batches
-- IDENTITY: COUNTRY_CODE + MEMBER_ID
-- ============================================================

UPDATE __MEMBER_CORE_TABLE__ C
SET
    EFFECTIVE_TO = P.FIRST_NEW_EFFECTIVE_FROM,
    IS_CURRENT = FALSE
FROM
(
    SELECT
        S.COUNTRY_CODE,
        S.MEMBER_ID,
        MIN(S.INGESTION_TIMESTAMP) AS FIRST_NEW_EFFECTIVE_FROM

    FROM __MEMBER_STAGING_TABLE__ S

    INNER JOIN __MEMBER_BATCH_CONTROL_TABLE__ B
        ON S.BATCH_ID = B.BATCH_ID

    WHERE B.STG_STATUS = 'SUCCESS'
      AND B.CORE_STATUS IN ('PENDING', 'FAILED')

      AND NOT EXISTS
      (
          SELECT 1
          FROM __MEMBER_CORE_TABLE__ C2
          WHERE C2.SOURCE_BATCH_ID = S.BATCH_ID
            AND C2.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER
      )

    GROUP BY
        S.COUNTRY_CODE,
        S.MEMBER_ID

) P

WHERE C.COUNTRY_CODE = P.COUNTRY_CODE
  AND C.MEMBER_ID = P.MEMBER_ID
  AND C.IS_CURRENT = TRUE;
