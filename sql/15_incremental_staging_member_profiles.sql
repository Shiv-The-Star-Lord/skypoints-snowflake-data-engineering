
USE DATABASE SKYPOINTS_DE;
USE SCHEMA STG;

INSERT INTO SKYPOINTS_DE.STG.STG_MEMBER_PROFILES
(
    MEMBER_NAME,
    MEMBER_ID,
    DATE_OF_BIRTH,
    AGE,
    TIER_CODE,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    STALE_MEMBER,
    AGENT_NAME,
    STATE_CODE,
    POSTAL_CODE,
    IS_ACTIVE,
    MEMBER_TYPE,
    COUNTRY_CODE,
    RECORD_HASH,
    INGESTION_TIMESTAMP,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    BATCH_ID
)

WITH PENDING_BATCHES AS
(
    SELECT C.BATCH_ID
    FROM SKYPOINTS_DE.OPS.MEMBER_BATCH_CONTROL C
    INNER JOIN SKYPOINTS_DE.OPS.INGESTION_AUDIT A
        ON C.BATCH_ID = A.BATCH_ID
    WHERE A.STATUS = 'SUCCESS'
      AND A.ENTITY_TYPE = 'MEMBER_PROFILE'
      AND C.STG_STATUS IN ('PENDING', 'FAILED')
),

HASHED_PENDING AS
(
    SELECT
        R.*,
        SHA2(
            TO_JSON(
                ARRAY_CONSTRUCT(
                    R.MEMBER_NAME,
                    R.MEMBER_ID,
                    R.DATE_OF_BIRTH,
                    R.TIER_CODE,
                    R.ENROLLMENT_DATE,
                    R.LAST_FLIGHT_DATE,
                    R.AGENT_NAME,
                    R.STATE_CODE,
                    R.POSTAL_CODE,
                    R.IS_ACTIVE,
                    R.MEMBER_TYPE,
                    R.COUNTRY_CODE
                )
            ),
            256
        ) AS RECORD_HASH

    FROM SKYPOINTS_DE.RAW.RAW_MEMBER_PROFILES R
    INNER JOIN PENDING_BATCHES P
        ON R.BATCH_ID = P.BATCH_ID
),

PENDING_MEMBERS AS
(
    SELECT DISTINCT MEMBER_NAME
    FROM HASHED_PENDING
),

LATEST_STG AS
(
    SELECT
        S.MEMBER_NAME,
        S.RECORD_HASH,
        S.INGESTION_TIMESTAMP,
        S.BATCH_ID,
        S.SOURCE_ROW_NUMBER

    FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES S
    INNER JOIN PENDING_MEMBERS P
        ON S.MEMBER_NAME = P.MEMBER_NAME

    QUALIFY ROW_NUMBER() OVER
    (
        PARTITION BY S.MEMBER_NAME
        ORDER BY
            S.INGESTION_TIMESTAMP DESC,
            S.BATCH_ID DESC,
            S.SOURCE_ROW_NUMBER DESC
    ) = 1
),

TIMELINE AS
(
    SELECT
        MEMBER_NAME,
        RECORD_HASH,
        INGESTION_TIMESTAMP,
        BATCH_ID,
        SOURCE_ROW_NUMBER,
        TRUE AS IS_BASELINE
    FROM LATEST_STG

    UNION ALL

    SELECT
        MEMBER_NAME,
        RECORD_HASH,
        INGESTION_TIMESTAMP,
        BATCH_ID,
        SOURCE_ROW_NUMBER,
        FALSE AS IS_BASELINE
    FROM HASHED_PENDING
),

ORDERED_TIMELINE AS
(
    SELECT
        *,
        LAG(RECORD_HASH) OVER
        (
            PARTITION BY MEMBER_NAME
            ORDER BY
                INGESTION_TIMESTAMP,
                BATCH_ID,
                SOURCE_ROW_NUMBER
        ) AS PREVIOUS_RECORD_HASH

    FROM TIMELINE
),

CHANGED_KEYS AS
(
    SELECT
        BATCH_ID,
        SOURCE_ROW_NUMBER
    FROM ORDERED_TIMELINE
    WHERE IS_BASELINE = FALSE
      AND
      (
          PREVIOUS_RECORD_HASH IS NULL
          OR RECORD_HASH <> PREVIOUS_RECORD_HASH
      )
)

SELECT
    R.MEMBER_NAME,
    R.MEMBER_ID,
    R.DATE_OF_BIRTH,

    CASE
        WHEN R.DATE_OF_BIRTH IS NOT NULL
        THEN
            DATEDIFF(YEAR, R.DATE_OF_BIRTH, CURRENT_DATE())
            - CASE
                WHEN DATEADD(
                    YEAR,
                    DATEDIFF(YEAR, R.DATE_OF_BIRTH, CURRENT_DATE()),
                    R.DATE_OF_BIRTH
                ) > CURRENT_DATE()
                THEN 1
                ELSE 0
              END
        ELSE NULL
    END AS AGE,

    R.TIER_CODE,
    R.ENROLLMENT_DATE,
    R.LAST_FLIGHT_DATE,

    CASE
        WHEN R.LAST_FLIGHT_DATE IS NULL THEN NULL
        WHEN DATEDIFF(
            DAY,
            R.LAST_FLIGHT_DATE,
            CURRENT_DATE()
        ) > 90 THEN TRUE
        ELSE FALSE
    END AS STALE_MEMBER,

    R.AGENT_NAME,
    R.STATE_CODE,
    R.POSTAL_CODE,
    R.IS_ACTIVE,
    R.MEMBER_TYPE,
    R.COUNTRY_CODE,
    R.RECORD_HASH,
    R.INGESTION_TIMESTAMP,
    R.SOURCE_FILE,
    R.SOURCE_ROW_NUMBER,
    R.BATCH_ID

FROM HASHED_PENDING R

INNER JOIN CHANGED_KEYS C
    ON R.BATCH_ID = C.BATCH_ID
   AND R.SOURCE_ROW_NUMBER = C.SOURCE_ROW_NUMBER

WHERE NOT EXISTS
(
    SELECT 1
    FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES S
    WHERE S.BATCH_ID = R.BATCH_ID
      AND S.SOURCE_ROW_NUMBER = R.SOURCE_ROW_NUMBER
);
