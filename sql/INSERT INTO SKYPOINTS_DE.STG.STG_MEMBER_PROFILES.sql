INSERT INTO SKYPOINTS_DE.STG.STG_MEMBER_PROFILES
(
    MEMBER_NAME,
    MEMBER_ID,
    DATE_OF_BIRTH,
    TIER_CODE,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    AGENT_NAME,
    STATE_CODE,
    POSTAL_CODE,
    IS_ACTIVE,
    MEMBER_TYPE,
    COUNTRY_CODE,
    RECORD_HASH,
    INGESTION_TIMESTAMP,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    BATCH_ID
)

WITH HASHED_RAW AS
(
    SELECT
        *,
        SHA2(
            TO_JSON(
                ARRAY_CONSTRUCT(
                    MEMBER_NAME,
                    MEMBER_ID,
                    DATE_OF_BIRTH,
                    TIER_CODE,
                    ENROLLMENT_DATE,
                    LAST_FLIGHT_DATE,
                    AGENT_NAME,
                    STATE_CODE,
                    POSTAL_CODE,
                    IS_ACTIVE,
                    MEMBER_TYPE,
                    COUNTRY_CODE
                )
            ),
            256
        ) AS RECORD_HASH

    FROM SKYPOINTS_DE.RAW.RAW_MEMBER_PROFILES
),

ORDERED_RAW AS
(
    SELECT
        *,
        LAG(RECORD_HASH) OVER
        (
            PARTITION BY MEMBER_NAME
            ORDER BY
                INGESTION_TIMESTAMP,
                BATCH_ID,
                SOURCE_ROW_NUMBER
        ) AS PREVIOUS_RECORD_HASH

    FROM HASHED_RAW
),

DEDUPLICATED AS
(
    SELECT *
    FROM ORDERED_RAW
    WHERE
        PREVIOUS_RECORD_HASH IS NULL
        OR RECORD_HASH <> PREVIOUS_RECORD_HASH
)

SELECT
    R.MEMBER_NAME,
    R.MEMBER_ID,
    R.DATE_OF_BIRTH,
    R.TIER_CODE,
    R.ENROLLMENT_DATE,
    R.LAST_FLIGHT_DATE,
    R.AGENT_NAME,
    R.STATE_CODE,
    R.POSTAL_CODE,
    R.IS_ACTIVE,
    R.MEMBER_TYPE,
    R.COUNTRY_CODE,
    R.RECORD_HASH,
    R.INGESTION_TIMESTAMP,
    R.SOURCE_FILE,
    R.SOURCE_ROW_NUMBER,
    R.BATCH_ID

FROM DEDUPLICATED R

WHERE NOT EXISTS
(
    SELECT 1
    FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES S
    WHERE S.BATCH_ID = R.BATCH_ID
      AND S.SOURCE_ROW_NUMBER = R.SOURCE_ROW_NUMBER
);




SELECT
    MEMBER_NAME,
    MEMBER_ID,
    COUNTRY_CODE,
    RECORD_HASH,
    INGESTION_TIMESTAMP,
    BATCH_ID
FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES
ORDER BY MEMBER_NAME;



SELECT
    MEMBER_NAME,
    COUNT(*) AS VERSION_COUNT,
    COUNT(DISTINCT RECORD_HASH) AS DISTINCT_VERSIONS
FROM SKYPOINTS_DE.STG.STG_MEMBER_PROFILES
GROUP BY MEMBER_NAME
ORDER BY MEMBER_NAME;